"""Search spaces = edge orbits of a permutation group (the "symmetry ladder").

A space maps one colour per edge orbit to a full colouring matrix that is invariant under
the group.  Rungs, from smallest to largest:

  cyclotomic / multiplier   translations of a group plus some of its automorphisms
                            (Paley, cubic-residue and similar colourings; a handful of orbits)
  Cayley                    one regular group G: cyclic (circulant), abelian, metacyclic
                            (dihedral, Frobenius, ...) or the additive group of GF(q)
  block Cayley              G acting regularly on each of b blocks, plus fixed points
  weak symmetry             a small group (often one involution): about n^2/(2|G|) orbits
  full                      every edge free, no symmetry
  extension                 a known colouring + new vertices; only the new edges are free

All groups are given by generator permutations, so every rung goes through the same code.
"""
from __future__ import annotations

from itertools import product
from math import gcd

import numpy as np


class Space:
    def __init__(self, n, orbits, sym, reps=None, rsz=None, base=None, name="", normalizer=None,
                 group_order=1):
        self.n = n
        self.orbits = [np.asarray(o, dtype=np.int32).reshape(-1, 2) for o in orbits]
        self.V = len(self.orbits)
        self.sym = bool(sym)      # True: counts via vertex-orbit representatives (C "sym" mode)
        self.name = name
        self.base = base          # full colouring used for frozen edges (or None)
        self.group_order = group_order
        sizes = np.array([len(o) for o in self.orbits], dtype=np.int32)
        self.sizes = sizes
        self.optr = np.zeros(self.V + 1, dtype=np.int32)
        self.optr[1:] = np.cumsum(sizes)
        flat = np.concatenate(self.orbits) if self.V else np.zeros((0, 2), np.int32)
        self.oedges = np.ascontiguousarray(flat.ravel(), dtype=np.int32)
        self.eu = np.ascontiguousarray(flat[:, 0])
        self.ev = np.ascontiguousarray(flat[:, 1])
        self.eo = np.repeat(np.arange(self.V, dtype=np.int32), sizes)
        self.first = flat[self.optr[:-1]] if self.V else np.zeros((0, 2), np.int32)
        if reps is not None:
            self.reps = np.ascontiguousarray(reps, dtype=np.int32)
            self.rsz = np.ascontiguousarray(rsz, dtype=np.int32)
        else:
            self.reps = self.rsz = None
        # vertex maps that normalise the group: used to align equivalent solutions (learner)
        self.normalizer = normalizer or []
        self._orbit_perms = None

    def __repr__(self):
        return f"Space({self.name}, n={self.n}, V={self.V}, sym={self.sym})"

    @property
    def singleton(self):
        return bool(self.V == 0 or self.sizes.max() == 1)

    def coloring_from_x(self, x) -> np.ndarray:
        n = self.n
        col = np.zeros((n, n), dtype=np.int8) if self.base is None else self.base.copy()
        x = np.asarray(x, dtype=np.int8)
        col[self.eu, self.ev] = x[self.eo]
        col[self.ev, self.eu] = x[self.eo]
        np.fill_diagonal(col, -1)
        return col

    def x_from_coloring(self, col) -> np.ndarray:
        return np.asarray(col[self.first[:, 0], self.first[:, 1]], dtype=np.int8)

    def is_invariant(self, col) -> bool:
        """True if every orbit is monochromatic in col."""
        col = np.asarray(col)
        x = self.x_from_coloring(col)
        return bool((col[self.eu, self.ev] == x[self.eo]).all())

    def orbit_perms(self):
        """Orbit permutations induced by the normaliser maps (identity first)."""
        if self._orbit_perms is None:
            n = self.n
            oid = -np.ones((n, n), dtype=np.int32)
            oid[self.eu, self.ev] = self.eo
            oid[self.ev, self.eu] = self.eo
            perms = [np.arange(self.V, dtype=np.int32)]
            for g in self.normalizer[:64]:
                g = np.asarray(g)
                p = oid[g[self.first[:, 0]], g[self.first[:, 1]]]
                if (p >= 0).all() and len(set(p.tolist())) == self.V:
                    perms.append(p.astype(np.int32))
            self._orbit_perms = perms
        return self._orbit_perms


def _closure(n, gens, cap=40000):
    """All elements of the group generated by `gens` (as rows), or None if more than `cap`."""
    ident = tuple(range(n))
    seen, frontier = {ident}, [ident]
    glist = [g.tolist() for g in gens]
    while frontier:
        p = frontier.pop()
        for g in glist:
            q = tuple(g[i] for i in p)        # q = g after p
            if q not in seen:
                seen.add(q)
                frontier.append(q)
                if len(seen) > cap:
                    return None
    return np.array(sorted(seen), dtype=np.int64)


def _orbits_slow(n, gens):
    glist = [g.tolist() for g in gens]
    eo = -np.ones((n, n), dtype=np.int64)
    orbits = []
    for u in range(n):
        for v in range(u + 1, n):
            if eo[u, v] >= 0:
                continue
            oid = len(orbits)
            eo[u, v] = oid
            members, stack = [(u, v)], [(u, v)]
            while stack:
                a, b = stack.pop()
                for g in glist:
                    x, y = g[a], g[b]
                    if x > y:
                        x, y = y, x
                    if eo[x, y] < 0:
                        eo[x, y] = oid
                        members.append((x, y))
                        stack.append((x, y))
            orbits.append(sorted(members))
    vo = -np.ones(n, dtype=np.int64)
    reps, rsz = [], []
    for v in range(n):
        if vo[v] >= 0:
            continue
        vo[v] = len(reps)
        stack, size = [v], 1
        while stack:
            a = stack.pop()
            for g in glist:
                b = g[a]
                if vo[b] < 0:
                    vo[b] = vo[v]
                    stack.append(b)
                    size += 1
        reps.append(v)
        rsz.append(size)
    return orbits, reps, rsz, None


def _orbits_from_generators(n, gens):
    """Edge orbits (ordered by their smallest edge) and vertex orbits of the group generated
    by the permutations `gens`.  Returns (orbits, reps, rep_orbit_sizes, group_order)."""
    gens = [np.asarray(g, dtype=np.int64) for g in gens]
    G = _closure(n, gens)
    if G is None:
        return _orbits_slow(n, gens)
    iu, iv = np.triu_indices(n, 1)
    lab = np.full(len(iu), n * n, dtype=np.int64)
    vlab = np.full(n, n, dtype=np.int64)
    for g in G:                                # label = smallest image under the group
        a, b = g[iu], g[iv]
        np.minimum(lab, np.minimum(a, b) * n + np.maximum(a, b), out=lab)
        np.minimum(vlab, g, out=vlab)
    _, inv = np.unique(lab, return_inverse=True)
    order = np.argsort(inv, kind="stable")
    pairs = np.stack([iu[order], iv[order]], axis=1)
    cuts = np.flatnonzero(np.diff(inv[order])) + 1
    orbits = np.split(pairs, cuts)
    reps, counts = np.unique(vlab, return_counts=True)
    return orbits, reps.tolist(), counts.tolist(), len(G)


def units(m):
    return [a for a in range(1, m) if gcd(a, m) == 1]


def group_space(n, gens, name="", normalizer=None, sym=True, group_order=None):
    orbits, reps, rsz, order = _orbits_from_generators(n, gens)
    return Space(n, orbits, sym, reps, rsz, name=name, normalizer=normalizer,
                 group_order=group_order or order or max(rsz))


# ------------------------------------------------------------------------------- groups
class Group:
    """A finite group in its left regular representation on {0..order-1}.

    gens   permutations generating the regular action
    autos  {label: permutation} group automorphisms (used to shrink spaces and to align
           equivalent solutions)
    """

    def __init__(self, name, order, gens, autos=None):
        self.name, self.order = name, order
        self.gens = [np.asarray(g, dtype=np.int64) for g in gens]
        self.autos = {k: np.asarray(v, dtype=np.int64) for k, v in (autos or {}).items()}


def cyclic_group(m):
    idx = np.arange(m)
    autos = {str(a): (a * idx) % m for a in units(m) if a != 1}
    return Group(f"Z{m}", m, [(idx + 1) % m], autos)


def abelian_group(dims):
    """Z_d1 x Z_d2 x ...; element (x1, x2, ...) has index x1*d2*d3*.. + x2*d3*.. + ..."""
    dims = [int(d) for d in dims]
    if len(dims) == 1:
        return cyclic_group(dims[0])
    m = int(np.prod(dims))
    coords = np.array(list(product(*[range(d) for d in dims])), dtype=np.int64)  # index order
    weights = np.array([int(np.prod(dims[j + 1:])) for j in range(len(dims))], dtype=np.int64)
    gens = []
    for j, d in enumerate(dims):
        c = coords.copy()
        c[:, j] = (c[:, j] + 1) % d
        gens.append(c @ weights)
    exp = int(np.lcm.reduce(dims))
    autos = {}
    for t in units(exp):
        if t != 1:
            autos[str(t)] = ((coords * t) % np.array(dims)) @ weights   # scalar multiplication
    return Group("Z" + "xZ".join(map(str, dims)), m, gens, autos)


def metacyclic_group(m, k, t):
    """Z_m x| Z_k with y x y^-1 = x^t (needs t^k = 1 mod m).  t = m-1, k = 2 is dihedral."""
    if pow(t, k, m) != 1 % m:
        raise ValueError("metacyclic group needs t^k = 1 (mod m)")
    c, d = np.divmod(np.arange(m * k), k)                  # element (c, d), index c*k + d
    lx = ((c + 1) % m) * k + d                             # x * (c, d)
    ly = ((t * c) % m) * k + (d + 1) % k                   # y * (c, d)
    autos = {str(u): ((u * c) % m) * k + d for u in units(m) if u != 1}
    name = f"D{m}" if (k == 2 and t == m - 1) else f"Z{m}:{k}t{t}"
    return Group(name, m * k, [lx, ly], autos)


def _is_prime(p):
    return p >= 2 and all(p % q for q in range(2, int(p ** 0.5) + 1))


def prime_power(q):
    """(p, k) if q = p^k with p prime, else None."""
    for p in range(2, q + 1):
        if q % p == 0:
            k, x = 0, q
            while x % p == 0:
                x //= p
                k += 1
            return (p, k) if x == 1 and _is_prime(p) else None
    return None


def field_group(q):
    """Additive group of GF(q), q = p^k, with multiplication by a primitive element as the
    automorphism 'mul' (its powers give the cyclotomic colourings).  For k = 1 this is Z_p."""
    pk = prime_power(q)
    if pk is None:
        raise ValueError("q must be a prime power")
    p, k = pk
    if k == 1:
        g = next(a for a in range(1, p) if len({pow(a, e, p) for e in range(1, p)}) == p - 1) if p > 2 else 1
        G = cyclic_group(p)
        G.autos["mul"] = (g * np.arange(p)) % p
        G.name = f"GF{p}"
        return G
    coords = np.array(list(product(range(p), repeat=k)), dtype=np.int64)   # coefficient of x^(k-1) first
    weights = np.array([p ** (k - 1 - j) for j in range(k)], dtype=np.int64)
    gens = []
    for j in range(k):
        c = coords.copy()
        c[:, j] = (c[:, j] + 1) % p
        gens.append(c @ weights)
    mul = None
    for tail in product(range(p), repeat=k):       # monic f = x^k + tail . (x^(k-1), ..., 1)
        # multiplication by x modulo f on coefficient vectors (a_{k-1}, ..., a_0)
        lead = coords[:, 0:1]
        shifted = np.concatenate([coords[:, 1:], np.zeros((q, 1), np.int64)], axis=1)
        cand = ((shifted - lead * np.array(tail)) % p) @ weights
        if len(set(cand.tolist())) != q:
            continue
        x, steps = int(cand[1]), 1                 # order of x: orbit of the element "1"
        while x != 1 and steps < q:
            x = int(cand[x])
            steps += 1
        if steps == q - 1:
            mul = cand
            break
    if mul is None:
        raise RuntimeError("no primitive polynomial found")
    return Group(f"GF{q}", q, gens, {"mul": mul})


def _abelian_dims(m):
    """All abelian groups of order m as lists of prime-power cyclic factors."""
    def partitions(e, cap=None):
        cap = e if cap is None else cap
        if e == 0:
            yield []
            return
        for first in range(min(e, cap), 0, -1):
            for rest in partitions(e - first, first):
                yield [first] + rest
    fac, x, p = [], m, 2
    while x > 1:
        if x % p == 0:
            e = 0
            while x % p == 0:
                x //= p
                e += 1
            fac.append((p, e))
        p += 1
    out = [[]]
    for p, e in fac:
        out = [o + [p ** a for a in part] for o in out for part in partitions(e)]
    return [sorted(o, reverse=True) for o in out]


def groups_of_order(m, nonabelian=True, limit=8):
    """A zero-knowledge catalogue: cyclic first, then the other abelian groups, then
    metacyclic ones (dihedral first).  Not every group of order m is of this form."""
    out = [cyclic_group(m)]
    for dims in _abelian_dims(m):
        if len(dims) > len({prime_power(d)[0] for d in dims}):   # some prime twice: not cyclic
            out.append(abelian_group(dims))
    if nonabelian:
        seen = set()
        for k in sorted(d for d in range(2, m) if m % d == 0):
            a = m // k
            if a < 3:
                continue
            for t in sorted(units(a), key=lambda t: (t != a - 1, t)):
                if t == 1 or pow(t, k, a) != 1:
                    continue
                sub = frozenset(pow(t, e, a) for e in range(k))
                if (a, k, sub) in seen:
                    continue
                seen.add((a, k, sub))
                out.append(metacyclic_group(a, k, t))
    return out[:limit]


# ------------------------------------------------------------------------------- spaces
def _lift(perm, m, blocks, fixed):
    """Apply a permutation of {0..m-1} inside each block; fixed points stay."""
    n = blocks * m + fixed
    g = np.arange(n, dtype=np.int64)
    for i in range(blocks):
        g[i * m:(i + 1) * m] = i * m + perm
    return g


def cayley_space(group, blocks=1, fixed=0, autos=(), sym=True):
    """`group` acting regularly on each of `blocks` blocks (vertex (i, g) = i*|G| + g) plus
    `fixed` fixed points.  `autos`: labels of group automorphisms that the colouring must
    also respect (applied to all blocks simultaneously), which shrinks the space."""
    m = group.order
    n = blocks * m + fixed
    gens = [_lift(g, m, blocks, fixed) for g in group.gens]
    gens += [_lift(group.autos[a], m, blocks, fixed) for a in autos]
    norm = [_lift(p, m, blocks, fixed) for p in group.autos.values()]
    name = group.name if blocks == 1 else f"{blocks}x{group.name}"
    if fixed:
        name += f"+{fixed}"
    if autos:
        name += "*" + ",".join(autos)
    return group_space(n, gens, name=name, normalizer=norm, sym=sym)


def circulant_space(n, multipliers=()):
    """Cayley colourings of Z_n; optional multipliers a (x -> a x) shrink the space further."""
    sp = cayley_space(cyclic_group(n), autos=tuple(str(a) for a in multipliers))
    sp.name = f"circ{n}" + (f"*{','.join(map(str, multipliers))}" if multipliers else "")
    return sp


def block_circulant_space(m, b, fixed=0, multipliers=()):
    """Z_m acting on b blocks of size m (vertex (i,x) = i*m+x), plus `fixed` fixed points."""
    sp = cayley_space(cyclic_group(m), blocks=b, fixed=fixed, autos=tuple(str(a) for a in multipliers))
    sp.name = f"block{b}x{m}" + (f"+{fixed}" if fixed else "") + (
        f"*{','.join(map(str, multipliers))}" if multipliers else "")
    return sp


def cyclotomic_space(q, e, field=None):
    """Space on GF(q): translations plus multiplication by g^e (g primitive).  The orbits are
    the cosets of <g^e, -1> in the multiplicative group (e = 2: Paley, e = 3: cubic residues)."""
    G = field or field_group(q)
    perm = np.arange(q)
    for _ in range(e):
        perm = G.autos["mul"][perm]
    H = Group(G.name, q, G.gens, {"m": perm})
    sp = cayley_space(H, autos=("m",))
    sp.name = f"GF{q}/{e}"
    return sp


def cyclotomic_spaces(q, max_orbits=40, min_orbits=2):
    """All cyclotomic spaces on GF(q) with a distinct number of orbits in the given range.
    Returns [(space, e)], fewest orbits first."""
    G = field_group(q)
    out, seen = [], set()
    for e in [d for d in range(2, q - 1) if (q - 1) % d == 0]:
        sp = cyclotomic_space(q, e, G)
        if not (min_orbits <= sp.V <= max_orbits) or sp.V in seen:
            continue
        seen.add(sp.V)
        out.append((sp, e))
    return sorted(out, key=lambda t: t[0].V)


def full_space(n):
    orbits = [[(u, v)] for u in range(n) for v in range(u + 1, n)]
    return Space(n, orbits, False, name=f"full{n}")


def extension_space(base_col, extra=1):
    """Keep the old graph frozen, make only the edges at `extra` new vertices free."""
    n0 = base_col.shape[0]
    n = n0 + extra
    base = np.zeros((n, n), dtype=np.int8)
    base[:n0, :n0] = base_col
    np.fill_diagonal(base, -1)
    orbits = [[(u, v)] for v in range(n0, n) for u in range(v)]
    return Space(n, orbits, False, base=base, name=f"ext{n0}+{extra}")


def multiplier_candidates(n, max_orbits=None, min_orbits=2):
    """Multipliers a giving distinct small orbit structures on Z_n distances (deduplicated)."""
    seen, out = set(), []
    for a in units(n):
        if a in (1, n - 1):
            continue
        H = {1, n - 1}
        frontier = list(H)
        while frontier:  # subgroup generated by a and -1
            x = frontier.pop()
            for y in ((x * a) % n, (x * (n - 1)) % n):
                if y not in H:
                    H.add(y)
                    frontier.append(y)
        key = frozenset(H)
        if key in seen:
            continue
        seen.add(key)
        done, cnt = set(), 0
        for d in range(1, n):
            if d in done:
                continue
            cnt += 1
            for h in H:
                done.add((h * d) % n)
        if cnt >= min_orbits and (max_orbits is None or cnt <= max_orbits):
            out.append((a, cnt))
    return sorted(out, key=lambda t: -t[1])


def _signature(sp):
    """Canonical fingerprint of the orbit partition (to drop duplicate spaces)."""
    n = sp.n
    oid = -np.ones((n, n), dtype=np.int64)
    oid[sp.eu, sp.ev] = sp.eo
    oid[sp.ev, sp.eu] = sp.eo
    flat = oid[np.triu_indices(n, 1)]
    _, first = np.unique(flat, return_index=True)
    relabel = np.empty(sp.V, dtype=np.int64)
    relabel[flat[np.sort(first)]] = np.arange(sp.V)
    return hash(relabel[flat].tobytes())


class SpaceSpec:
    """A symmetric space that is only built when first used.

    est_v: estimated number of orbits.  weight: relative share of search time (1 = normal)."""

    def __init__(self, name, est_v, build, weight=1.0):
        self.name, self.est_v, self._build, self._space = name, est_v, build, None
        self.weight = weight

    def space(self):
        if self._space is None:
            self._space = self._build()
            self._space.name = self.name
            self._build = None
        return self._space


def symmetric_catalogue(n, max_blocks=6, max_fixed=2, nonabelian=True, groups_per_order=8,
                        min_order=4, max_spaces=64):
    """Specs of all symmetric spaces this program knows for n vertices, ordered by the
    estimated number of orbits (smallest first).

    Shapes: `blocks` copies of a group of order m plus `fixed` fixed points, blocks*m + fixed
    = n.  Groups: cyclic, abelian, metacyclic.  For one block also the multiplier / cyclotomic
    sub-spaces (a handful of orbits).  Two specs can describe the same orbit partition; use
    _signature(space) to drop duplicates once they are built.

    One block plus fixed points gets weight 1/4: all edges from a fixed vertex to the block
    form a single orbit, so that vertex is joined to everything in one colour c and the block
    must avoid K_{k_c - 1} in colour c.  That is a colouring for a smaller clique size on
    almost as many vertices, which exists only well below the size being attacked.
    """
    out, names = [], set()

    def add(name, est, build, weight=1.0):
        if name not in names:
            names.add(name)
            out.append(SpaceSpec(name, est, build, weight))

    for a, cnt in multiplier_candidates(n, max_orbits=24, min_orbits=2)[-8:]:
        add(f"circ{n}*{a}", cnt, lambda a=a: circulant_space(n, (a,)))
    pk = prime_power(n)
    if pk and pk[1] > 1:
        for e in [d for d in range(2, n - 1) if (n - 1) % d == 0 and d <= 48]:
            add(f"GF{n}/{e}", e, lambda e=e: cyclotomic_space(n, e))
    for fixed in range(0, max_fixed + 1):
        for blocks in range(1, max_blocks + 1):
            m, rem = divmod(n - fixed, blocks)
            if rem or m < min_order or (blocks == 1 and fixed > 0 and m < 2 * min_order):
                continue
            est = blocks * (m - 1) / 2 + blocks * (blocks - 1) * m / 2 + fixed * blocks + fixed * (fixed - 1) / 2
            for G in groups_of_order(m, nonabelian=nonabelian, limit=groups_per_order):
                name = f"circ{n}" if (blocks == 1 and fixed == 0 and len(G.gens) == 1) else (
                    (G.name if blocks == 1 else f"{blocks}x{G.name}") + (f"+{fixed}" if fixed else ""))
                add(name, est + 0.01 * len(out), lambda G=G, b=blocks, f=fixed: cayley_space(G, blocks=b, fixed=f),
                    weight=0.25 if (blocks == 1 and fixed > 0) else 1.0)
    out.sort(key=lambda sp: sp.est_v)
    return out[:max_spaces]
